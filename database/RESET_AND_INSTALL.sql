-- Create a manual-payment order using the live package price/credit values, never browser values.
create or replace function public.create_manual_order(
  p_package_id bigint,
  p_payment_method text,
  p_sender_phone text,
  p_transaction_ref text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := auth.uid(); v_pkg public.packages%rowtype; v_method public.payment_methods%rowtype; v_tx public.transactions%rowtype;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if length(trim(coalesce(p_sender_phone,''))) < 8 or length(trim(coalesce(p_transaction_ref,''))) < 5 then
    raise exception 'Valid sender phone and transaction reference are required';
  end if;
  select * into v_pkg from public.packages where id=p_package_id and is_active=true;
  if not found then raise exception 'Package is unavailable'; end if;
  select * into v_method from public.payment_methods where code=lower(trim(p_payment_method)) and is_active=true;
  if not found then raise exception 'Payment method is unavailable'; end if;
  insert into public.transactions(user_id, package_id, amount_bdt, credits_added, payment_method, payment_ref, sender_phone, status, payment_channel)
  values(v_uid, v_pkg.id, v_pkg.price_bdt, v_pkg.credits, v_method.code, trim(p_transaction_ref), trim(p_sender_phone), 'pending', 'manual')
  returning * into v_tx;
  return jsonb_build_object('id',v_tx.id,'status',v_tx.status,'amount_bdt',v_tx.amount_bdt,'credits_added',v_tx.credits_added);
exception when unique_violation then raise exception 'This transaction reference has already been submitted';
end; $$;

-- Atomic, one-time admin approval. Duplicate approvals cannot credit twice.
create or replace function public.admin_review_transaction(p_transaction_id uuid, p_approve boolean, p_note text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_tx public.transactions%rowtype;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select * into v_tx from public.transactions where id=p_transaction_id for update;
  if not found then raise exception 'Transaction not found'; end if;
  if v_tx.status <> 'pending' then raise exception 'Transaction is already reviewed'; end if;
  if p_approve then
    update public.user_credits set credits_remaining=credits_remaining+v_tx.credits_added,
      total_purchased=total_purchased+v_tx.credits_added where user_id=v_tx.user_id;
    update public.transactions set status='completed', verified_by=auth.uid(), verified_at=now(), admin_note=p_note where id=v_tx.id;
  else
    update public.transactions set status='rejected', verified_by=auth.uid(), verified_at=now(), admin_note=p_note where id=v_tx.id;
  end if;
  return jsonb_build_object('success',true,'status',case when p_approve then 'completed' else 'rejected' end);
end; $$;

-- Atomic credit debit, request id prevents retrying same operation twice.
create table public.api_rate_limits (
  bucket_key text primary key,
  window_started_at timestamptz not null,
  request_count integer not null default 0 check (request_count >= 0)
);

create or replace function public.check_lookup_rate_limit(p_user_id uuid, p_bucket_key text, p_limit integer default 5)
returns boolean language plpgsql security definer set search_path = '' as $$
declare v_count integer;
begin
  if coalesce(auth.role(),'') <> 'service_role' then raise exception 'Service role required'; end if;
  insert into public.api_rate_limits(bucket_key,window_started_at,request_count)
  values(p_bucket_key,now(),1)
  on conflict(bucket_key) do update set
    window_started_at=case when public.api_rate_limits.window_started_at < now()-interval '1 minute' then now() else public.api_rate_limits.window_started_at end,
    request_count=case when public.api_rate_limits.window_started_at < now()-interval '1 minute' then 1 else public.api_rate_limits.request_count+1 end
  returning request_count into v_count;
  return v_count <= greatest(1,least(p_limit,30));
end; $$;

create table public.credit_operations (
  request_id uuid primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  operation text not null check (operation in ('debit','refund')),
  created_at timestamptz not null default now()
);

create or replace function public.consume_one_credit(p_user_id uuid, p_request_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := auth.uid(); v_left integer;
begin
  if coalesce(auth.role(),'') <> 'service_role' and (v_uid is null or v_uid <> p_user_id) then raise exception 'Not authorized'; end if;
  insert into public.credit_operations(request_id,user_id,operation) values(p_request_id,p_user_id,'debit') on conflict do nothing;
  if not found then raise exception 'Duplicate request'; end if;
  update public.user_credits set credits_remaining=credits_remaining-1,total_used=total_used+1
  where user_id=p_user_id and credits_remaining>0 returning credits_remaining into v_left;
  if not found then delete from public.credit_operations where request_id=p_request_id; return jsonb_build_object('success',false); end if;
  return jsonb_build_object('success',true,'credits_remaining',v_left);
end; $$;

create or replace function public.refund_one_credit(p_user_id uuid, p_request_id uuid)
returns boolean language plpgsql security definer set search_path = '' as $$
declare v_op public.credit_operations%rowtype;
begin
  if coalesce(auth.role(),'') <> 'service_role' and auth.uid() is distinct from p_user_id then raise exception 'Not authorized'; end if;
  select * into v_op from public.credit_operations where request_id=p_request_id and user_id=p_user_id for update;
  if not found or v_op.operation <> 'debit' then return false; end if;
  update public.user_credits set credits_remaining=credits_remaining+1,total_used=greatest(total_used-1,0) where user_id=p_user_id;
  update public.credit_operations set operation='refund' where request_id=p_request_id;
  return true;
end; $$;

-- Admin-only credit adjustment; signed deltas are audited through this RPC boundary.
create or replace function public.admin_adjust_credits(p_user_id uuid, p_delta integer)
returns integer language plpgsql security definer set search_path = '' as $$
declare v_left integer;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  if p_delta=0 or abs(p_delta)>1000000 then raise exception 'Invalid adjustment'; end if;
  update public.user_credits set credits_remaining=credits_remaining+p_delta,
    total_purchased=case when p_delta>0 then total_purchased+p_delta else total_purchased end
  where user_id=p_user_id and credits_remaining+p_delta>=0 returning credits_remaining into v_left;
  if not found then raise exception 'User not found or insufficient credits'; end if;
  return v_left;
end; $$;

create or replace function public.admin_set_user_role(p_user_id uuid, p_role text)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  if p_role not in ('user','admin') then raise exception 'Invalid role'; end if;
  update public.profiles set role=p_role where id=p_user_id;
  if not found then raise exception 'User not found'; end if;
  return true;
end; $$;

create or replace function public.admin_grant_package(p_user_id uuid, p_package_id bigint)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_pkg public.packages%rowtype; v_tx public.transactions%rowtype;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select * into v_pkg from public.packages where id=p_package_id and is_active=true;
  if not found then raise exception 'Active package not found'; end if;
  update public.user_credits set credits_remaining=credits_remaining+v_pkg.credits,
    total_purchased=total_purchased+v_pkg.credits where user_id=p_user_id;
  if not found then raise exception 'User credit record not found'; end if;
  insert into public.transactions(user_id,package_id,amount_bdt,credits_added,payment_method,payment_ref,status,payment_channel,verified_by,verified_at,admin_note)
  values(p_user_id,v_pkg.id,0,v_pkg.credits,'admin',null,'completed','manual',auth.uid(),now(),'Package granted by administrator')
  returning * into v_tx;
  return jsonb_build_object('transaction_id',v_tx.id,'credits_added',v_pkg.credits);
end; $$;

