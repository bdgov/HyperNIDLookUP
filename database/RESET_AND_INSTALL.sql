-- Admin identity is read from a protected server-side profile row.
create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin'
  );
$$;

-- Secure signup trigger. New users can never choose their own role.
create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  insert into public.profiles(id, full_name, email, role)
  values (new.id, nullif(new.raw_user_meta_data->>'full_name',''), new.email, 'user')
  on conflict (id) do nothing;
  insert into public.user_credits(user_id, credits_remaining, total_purchased, total_used)
  values (new.id, 0, 0, 0)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- Backfill profiles/credits for accounts that existed before this reset.
